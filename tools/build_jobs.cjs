// Builds tools/jobs.json (for gen_voices.py) and audio/voices.js (text -> file map loaded by the app)
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const root = path.join(__dirname, "..");
const P = JSON.parse(fs.readFileSync(path.join(__dirname, "phrases.json"), "utf8"));
const slug = (t, kind) => {
  const s = t.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return kind === "word" ? s : s.slice(0, 40).replace(/-$/, "") + "-" + crypto.createHash("sha1").update(t).digest("hex").slice(0, 6);
};
const items = [], en = {}, es = {};
for (const w of P.words) { const f = `en/${slug(w, "word")}.mp3`; items.push({ text: w, lang: "en", file: f, kind: "word" }); en[w] = f; }
for (const s of P.sentences) { const f = `en/s/${slug(s, "s")}.mp3`; items.push({ text: s, lang: "en", file: f, kind: "sentence" }); en[s] = f; }
for (const [, w] of P.vocab_es) { if (es[w]) continue; const f = `es/${slug(w, "word")}.mp3`; items.push({ text: w, lang: "es", file: f, kind: "word" }); es[w] = f; }
// group by language so the model is loaded once per language
items.sort((a, b) => a.lang.localeCompare(b.lang));
fs.writeFileSync(path.join(__dirname, "jobs.json"), JSON.stringify({ out: path.join(root, "audio"), seed: 1234, items }, null, 1));
fs.mkdirSync(path.join(root, "audio"), { recursive: true });
fs.writeFileSync(path.join(root, "audio", "voices.js"), "// generated by tools/build_jobs.cjs\nwindow.VOICES=" + JSON.stringify({ en, es }) + ";\n");
console.log(items.length, "clips");
